"""Referee: upper construction for the rank word w = 001001110010110001101101 on 2^[23].

The table C(i,j) = w[i+j] colours S by w[|S|] for every split, so the claim is split-independent.
1. Check the two shipped 14-families (distinct, closed, monochromatic, size 14) -- data/upper/upper_n23.json.
2. Exact maximum of a monochromatic sublattice for a rank word, my own method:
   weighted-poset representation (Birkhoff): family ranks = beta + w(D), D ideal of P.
   P = ordinal sum of incomparability-connected components; DP over ranks glues components.
   Connected components are generated by connected-prefix linear extensions (each new element
   incomparable to some earlier one); any component reaching >= LIMIT ideals is reported.
3. Brute-force control: for n <= 5, every rank word, enumerate all sublattices of 2^[n] directly.
Usage: upper_check.py DATA_DIR
"""
import json
import sys
from itertools import combinations

LIMIT = 15  # we want to know whether 15 is reachable


def exact_rank_max(word, c, cap=LIMIT):
    """Return (max size, found_big) for colour c. found_big=True if some component reached >= cap."""
    n = len(word) - 1
    R = [word[r] == c for r in range(n + 1)]
    # comp[s] = dict t -> max |J(C)| over connected components (>=1 element) from rank s to rank t
    comp = [dict() for _ in range(n + 1)]
    big = [False]

    def grow(s, ideals, preds_ok, total, k):
        # ideals: list of (mask, weight); elements count k
        J = len(ideals)
        t = s + total
        if k >= 1:
            if J > comp[s].get(t, 0):
                comp[s][t] = J
            if J >= cap:
                big[0] = True
                return
        if k >= 9:
            return
        full = (1 << k) - 1
        for (I, wI) in list(ideals):
            if k >= 1 and I == full:
                continue  # would add no incomparability: not connected (chain links handled as k=1)
            ups = [(D, wD) for (D, wD) in ideals if D & I == I]
            for w in range(1, n - s - total + 1):
                ok = True
                for (D, wD) in ups:
                    if not R[s + wD + w]:
                        ok = False
                        break
                if not ok:
                    continue
                if J + len(ups) > 2 * cap:
                    continue
                new = ideals + [(D | (1 << k), wD + w) for (D, wD) in ups]
                grow(s, new, None, total + w, k + 1)
                if big[0]:
                    return

    for s in range(n + 1):
        if not R[s]:
            continue
        # first element: from the empty ideal (only ideal)
        grow(s, [(0, 0)], None, 0, 0)
        if big[0]:
            return None, True
    # note: k=1 components are single elements (chain links), J=2.
    h = [0] * (n + 1)
    for r in range(n + 1):
        if R[r]:
            h[r] = max(h[r], 1)
            for t, J in comp[r].items():
                if t > r:
                    h[t] = max(h[t], h[r] + J - 1)
    return max(h), False


def brute(word, c):
    n = len(word) - 1
    U = 1 << n
    elems = [x for x in range(U) if word[bin(x).count("1")] == c]
    best = 0
    seen = set()
    stack = []
    for x in elems:
        L = frozenset([x])
        if L not in seen:
            seen.add(L)
            stack.append(L)
    eset = set(elems)
    while stack:
        L = stack.pop()
        best = max(best, len(L))
        for y in elems:
            if y in L:
                continue
            S = set(L) | {y}
            changed = True
            okc = True
            while changed:
                changed = False
                for a, b in combinations(list(S), 2):
                    for z in (a | b, a & b):
                        if z not in S:
                            if z not in eset:
                                okc = False
                                break
                            S.add(z)
                            changed = True
                    if not okc:
                        break
                if not okc:
                    break
            if okc:
                F = frozenset(S)
                if F not in seen:
                    seen.add(F)
                    stack.append(F)
    return best


def check_family(fam, word):
    s = set(fam)
    assert len(s) == len(fam)
    for a, b in combinations(fam, 2):
        assert (a | b) in s and (a & b) in s
    cols = {word[bin(x).count("1")] for x in fam}
    assert all(0 <= x < 1 << (len(word) - 1) for x in fam)
    return len(fam), cols


def main(dd):
    up = json.load(open(f"{dd}/upper/upper_n23.json"))
    word = up["word"]
    assert word == "001001110010110001101101" and len(word) == 24
    for col in up["colours"]:
        size, cols = check_family(col["witness"], word)
        print(f"colour {col['colour']}: shipped family size {size}, colours {cols}, closed: yes")
    # brute-force control
    mism = 0
    tested = 0
    for n in range(0, 6):
        for m in range(1 << (n + 1)):
            wd = "".join("1" if m >> r & 1 else "0" for r in range(n + 1))
            for c in "01":
                if c not in wd:
                    continue
                b = brute(wd, c)
                e, big = exact_rank_max(wd, c, cap=10 ** 6)
                tested += 1
                if b != e:
                    mism += 1
                    print("MISMATCH", wd, c, b, e)
    print(f"brute-force control n<=5: {tested} (word,colour) cases, {mism} mismatches")
    # known values
    for wd in ["0010011100101100011011", "0011001011100010110011",
               "1100110100011101001100", "1101100011010011100100"]:
        print(wd, "exact maxima", [exact_rank_max(wd, c)[0] for c in "01"])
    for c in "01":
        e, big = exact_rank_max(word, c, cap=LIMIT)
        print(f"n=23 word {word} colour {c}: exact max {e}, component reaching 15: {big}")


if __name__ == "__main__":
    main(sys.argv[1])
