 # Plant arbitrary weighted naturally labelled posets within n. The direct family
 # is generated by enumerating subsets against the relation, not search recurrence.
 for n in range(15,21):
  for j in range(100):
   k=rng.randrange(1,7);pred=[]
   for i in range(k):
    p=0
    for h in range(i):
     if rng.randrange(2):p|=(1<<h)|pred[h]
    pred.append(p)
   weights=[1]*k
   for q in range(rng.randrange(n-k+1)):weights[rng.randrange(k)]+=1
   a=rng.randrange(n-sum(weights)+1);blocks=[];shift=a
   for w in weights:blocks.append(((1<<w)-1)<<shift);shift+=w
   family=[]
   for D in range(1<<k):
    if all(not(D>>i&1) or pred[i]&D==pred[i] for i in range(k)):
     S=(1<<a)-1
     for i in range(k):
      if D>>i&1:S|=blocks[i]
     family.append(S)
   ranks={S.bit_count() for S in family};word=''.join('1' if i in ranks else '0' for i in range(n+1))
   witness(n,word,1,len(family),family);assert r.decide(word,1,len(family))['found']
  print('PLANTED',n,100,'passed',flush=True)
