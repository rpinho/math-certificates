"""Python brute force oracle versus independent C++ pruning and cover checking."""
from pathlib import Path
import random,subprocess,json
root=Path('/workspace/ref_hugo_HB01');folder=root/'controls';folder.mkdir(exist_ok=True)
rng=random.Random(382045);receipts=[]
def run(args):
    r=subprocess.run([str(root/'referee')]+list(map(str,args)),capture_output=True,text=True)
    return r.returncode,r.stdout,r.stderr
for case in range(80):
    n=rng.randint(3,8);start=rng.randint(0,3);end=start+rng.randint(5,28)
    # Integral centi-coordinates with coincident nodes exercise nonmetric floor travel.
    xy=[(rng.randrange(0,8),rng.randrange(0,8)) for _ in range(n)] if case%3 else [(0,0)]*n
    svc=[0]+[rng.randrange(0,5) for _ in range(n-1)];prof=[0]+[rng.randrange(0,10) for _ in range(n-1)]
    op=[start]+[rng.randrange(start,end+1) for _ in range(n-1)]
    cl=[end]+[rng.randrange(op[j],end+1) for j in range(1,n)]
    rows=[f'20 1 {case%7} {n-1} 0 0 '+' '.join(['0']*10),f'0 {xy[0][0]/100:.2f} {xy[0][1]/100:.2f} 0 0 {start/100:.2f} {end/100:.2f}']
    for j in range(1,n):rows.append(f'{j} {xy[j][0]/100:.2f} {xy[j][1]/100:.2f} {svc[j]/100:.2f} {prof[j]} 0 '+' '.join([f'{op[j]/100:.2f} {cl[j]/100:.2f}']*7)+' 0')
    raw=folder/f'c{case}.txt';raw.write_text('\n'.join(rows)+'\n')
    from math import isqrt
    d=[[isqrt((a[0]-b[0])**2+(a[1]-b[1])**2) for b in xy] for a in xy]
    states=[];best=[0,[0,0]]
    def brute(i,t,p,visited,path):
        states.append((i,t,p,visited))
        if t+d[i][0]<=end and p>=best[0]:best[:]=[p,path+[0]]
        for j in range(1,n):
            if visited>>j&1:continue
            st=max(t+d[i][j],op[j]);
            if st<=cl[j] and st+svc[j]<=end:brute(j,st+svc[j],p+prof[j],visited|1<<j,path+[j])
    brute(0,start,0,1,[0]);opt,path=best
    for mode in ['plain','dfs']:
        rc,out,err=run([mode,raw]);assert rc==0,(case,mode,err)
        assert json.loads(out)['optimum']==opt,(case,mode,opt,out)
    # Full-memory certificates are generated by the unrelated brute oracle.
    def proof(upper,primal):
        lines=['NGBOUND2',f'{n} {opt if primal else 0} {upper}']
        lines += [f'{n} '+' '.join(map(str,range(n))) for _ in range(n)]
        lines += [str(len(states))]+[' '.join(map(str,s)) for s in states]
        tour=path if primal else [0,0];lines+= [str(len(tour))+' '+' '.join(map(str,tour))]
        return '\n'.join(lines)+'\n'
    cert=folder/f'c{case}.proof';cert.write_text(proof(opt,True))
    rc,out,err=run(['cover',raw,cert]);assert rc==0,(case,'true cover',err)
    if opt>0:
        cert.write_text(proof(opt-1,False));rc,out,err=run(['cover',raw,cert]);assert rc!=0,(case,'false upper accepted')
    receipts.append(dict(case=case,n=n,optimum=opt,oracle_prefixes=len(states),false_upper_rejected=opt>0))
(root/'controls.json').write_text(json.dumps(dict(status='PASS',fixtures=receipts),indent=2))
print('PASS',len(receipts),'brute-force/pruning/cover cases;',sum(r['false_upper_rejected'] for r in receipts),'false uppers rejected')
